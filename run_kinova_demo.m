function summary=run_kinova_demo()
%RUN_KINOVA_DEMO Validate, simulate, check integration and save readable outputs.
root=setup_kinova();addpath(fullfile(root,'tests'),fullfile(root,'tools'),fullfile(root,'examples'));
validation=validate_kinova();m=kinova.model();c=kinova.config();log=kinova.simulate(m,c);
refined=c;refined.substeps=2*c.substeps;fine=kinova.simulate(m,refined);
stepcheck=struct('same_control_dt_s',c.control_dt,'coarse_plant_step_s',c.control_dt/c.substeps, ...
    'fine_plant_step_s',refined.control_dt/refined.substeps, ...
    'max_q_difference_rad',max(abs(log.q-fine.q),[],'all'), ...
    'max_dq_difference_rad_s',max(abs(log.dq-fine.dq),[],'all'), ...
    'coarse_energy_error_J',log.metrics.energy_balance_max_error_J, ...
    'fine_energy_error_J',fine.metrics.energy_balance_max_error_J);
stepcheck.pass=stepcheck.max_q_difference_rad<1e-5&&stepcheck.max_dq_difference_rad_s<1e-4 ...
    &&stepcheck.coarse_energy_error_J<1e-5;
summary=struct('validation',validation,'nominal',log.metrics,'step_refinement',stepcheck, ...
    'pass',validation.pass&&stepcheck.pass&&log.metrics.maximum_stage_limit_violation_rad<=0 ...
    &&log.metrics.max_stage_velocity_utilization<=1&&log.metrics.max_command_utilization<=1+1e-12, ...
    'scope','Mechanical simulation with approximate actuator inertia. Numerical validation, not a hardware validation.');
assert(summary.pass,'kinova:demo','Demo checks failed');
if c.save_results
    out=fullfile(root,'results');save(fullfile(out,'demo.mat'),'log','m','c');
    kinova.write_json(fullfile(out,'summary.json'),summary);kinova.plot_results(log,m,out);
end
disp(log.metrics);disp(stepcheck);
end
